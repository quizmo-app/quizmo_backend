"""SQLite access helpers: connections, schema and atomic transactions."""

import sqlite3
from collections.abc import Iterator
from contextlib import contextmanager, suppress
from datetime import datetime, timezone
from pathlib import Path

from app.exceptions import InternalStorageError

SCHEMA = """
CREATE TABLE IF NOT EXISTS courses (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    title TEXT NOT NULL,
    owner_ldap TEXT NOT NULL,
    is_archived INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_courses_owner ON courses(owner_ldap);

CREATE TABLE IF NOT EXISTS course_versions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    version_number INTEGER NOT NULL,
    page_count INTEGER NOT NULL,
    is_active INTEGER NOT NULL,
    page_fingerprints TEXT NOT NULL,
    created_at TEXT NOT NULL,
    UNIQUE (course_id, version_number)
);

CREATE TABLE IF NOT EXISTS quizzes (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    mode TEXT NOT NULL DEFAULT 'NOTE',
    default_duration INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS questions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    quiz_id INTEGER NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    type TEXT NOT NULL,
    statement TEXT NOT NULL,
    duration INTEGER NOT NULL,
    configuration TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS leaderboards (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS insertions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    id_version INTEGER NOT NULL REFERENCES course_versions(id) ON DELETE CASCADE,
    type_element TEXT NOT NULL CHECK (type_element IN ('QUIZ', 'LEADERBOARD')),
    id_quiz INTEGER REFERENCES quizzes(id) ON DELETE CASCADE,
    id_leaderboard INTEGER REFERENCES leaderboards(id) ON DELETE CASCADE,
    apres_page INTEGER NOT NULL,
    ordre INTEGER NOT NULL,
    empreinte TEXT NOT NULL,
    UNIQUE (id_version, apres_page, ordre)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_insertions_version_quiz
    ON insertions(id_version, id_quiz) WHERE id_quiz IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_insertions_version ON insertions(id_version);

CREATE TABLE IF NOT EXISTS presentations (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    version_id INTEGER NOT NULL REFERENCES course_versions(id) ON DELETE CASCADE,
    state TEXT NOT NULL
        CHECK (state IN ('EN_PRESENTATION', 'QUIZ_EN_COURS', 'INTERROMPUE', 'TERMINEE')),
    current_position INTEGER NOT NULL DEFAULT 1,
    started_at TEXT NOT NULL,
    ended_at TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_presentations_active
    ON presentations(course_id) WHERE state <> 'TERMINEE';
"""


def connect(database_path: Path) -> sqlite3.Connection:
    """Open a connection in autocommit mode with foreign keys and busy timeout enforced."""
    connection = sqlite3.connect(
        database_path, timeout=30.0, isolation_level=None, check_same_thread=False
    )
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    connection.execute("PRAGMA busy_timeout = 30000")
    return connection


def init_db(database_path: Path) -> None:
    """Create the parent folder and every table (idempotent)."""
    database_path.parent.mkdir(parents=True, exist_ok=True)
    connection = connect(database_path)
    try:
        connection.execute("PRAGMA journal_mode = WAL")
        connection.executescript(SCHEMA)
    finally:
        connection.close()


def utc_now() -> str:
    """Current UTC time as an ISO-8601 string."""
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def inserted_id(cursor: sqlite3.Cursor) -> int:
    """Primary key generated by the last INSERT."""
    if cursor.lastrowid is None:
        raise InternalStorageError()
    return cursor.lastrowid


def _rollback(connection: sqlite3.Connection) -> None:
    with suppress(sqlite3.Error):
        connection.execute("ROLLBACK")


@contextmanager
def transaction(connection: sqlite3.Connection) -> Iterator[sqlite3.Connection]:
    """All-or-nothing block; database errors become ``InternalStorageError`` (E10)."""
    try:
        connection.execute("BEGIN IMMEDIATE")
        yield connection
        connection.execute("COMMIT")
    except sqlite3.Error as exc:
        _rollback(connection)
        raise InternalStorageError() from exc
    except BaseException:
        _rollback(connection)
        raise
